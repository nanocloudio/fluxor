// Contract: input::key — Keyboard event surface.
//
// Layer: contracts/input (public, stable).
//
// Wire shape modelled on the W3C UIEvents `KeyboardEvent` spec:
// physical-key + logical-key + modifier reporting on a single
// channel. Producers are whatever holds a keyboard: the browser DOM
// (wasm_browser_keyboard), a host window, a hardware scan-code reader.
//
// Record (fixed 8 bytes, little-endian):
//
//   [0]     msg_type    MSG_EVENT
//   [1]     event_kind  KIND_DOWN | KIND_UP
//   [2]     modifiers   MOD_* bits
//   [3]     flags       KEY_REPEAT | KEY_TEXT; other bits zero
//   [4..6]  key_code    u16
//   [6..8]  scan_code   u16
//
// `key_code` is the W3C `KeyboardEvent.keyCode` (logical key after
// keymap). `scan_code` is the physical scan code (USB HID usage,
// or evdev keycode). The rule of thumb: games and emulators care about
// scan_code (physical, layout-independent); terminals and text editors
// care about key_code.
//
// KEYS AND TEXT, NEVER TWICE. `KEY_TEXT` says this key's effect arrived on
// `TextEvents` (`input::text`): an insert, a deletion, a paste. While a
// consumer's own text target has focus it applies `TextEvents` and ignores
// the editing effect of `KEY_TEXT` keys; a key without the flag is the
// consumer's to handle, editing keys included. With no text target focused
// it handles keys as keys whatever the flag.

/// Total event size in bytes.
pub const EVENT_SIZE: usize = 8;

/// Byte offsets of the record's fields.
pub const OFF_MSG_TYPE: usize = 0;
pub const OFF_EVENT_KIND: usize = 1;
pub const OFF_MODIFIERS: usize = 2;
pub const OFF_FLAGS: usize = 3;
pub const OFF_KEY_CODE: usize = 4;
pub const OFF_SCAN_CODE: usize = 6;

// ── Downstream: producer → consumer ──────────────────────────────────

/// Key state transition. Producers emit on KeyDown / KeyUp.
pub const MSG_EVENT: u8 = 0x01;

// ── Event kinds (msg.event_kind byte) ────────────────────────────────

pub const KIND_DOWN: u8 = 1;
pub const KIND_UP: u8 = 2;

// ── Modifier bitfield (msg.modifiers) ────────────────────────────────
// Same numeric layout as input::pointer::MOD_* so a single
// modifier-state byte can be shared if a transformer fuses
// pointer + key state.

pub const MOD_SHIFT: u8 = 0x01;
pub const MOD_CTRL: u8 = 0x02;
pub const MOD_ALT: u8 = 0x04;
pub const MOD_META: u8 = 0x08;

// ── Flags (msg.flags) ────────────────────────────────────────────────

/// A KeyDown generated by autorepeat.
pub const KEY_REPEAT: u8 = 0x01;
/// The key's effect arrived on `TextEvents`.
pub const KEY_TEXT: u8 = 0x02;
const FLAGS_KNOWN: u8 = KEY_REPEAT | KEY_TEXT;

/// One key record, by field.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct KeyEvent {
    pub kind: u8,
    pub modifiers: u8,
    /// Generated by autorepeat (`KEY_REPEAT`).
    pub repeat: bool,
    /// The key's effect arrived on `TextEvents` (`KEY_TEXT`).
    pub text: bool,
    pub key_code: u16,
    pub scan_code: u16,
}

/// Read a record. `None` for a message type other than `MSG_EVENT` or a
/// flags byte with a bit this contract does not allocate.
pub const fn decode(b: &[u8; EVENT_SIZE]) -> Option<KeyEvent> {
    if b[OFF_MSG_TYPE] != MSG_EVENT || b[OFF_FLAGS] & !FLAGS_KNOWN != 0 {
        return None;
    }
    Some(KeyEvent {
        kind: b[OFF_EVENT_KIND],
        modifiers: b[OFF_MODIFIERS],
        repeat: b[OFF_FLAGS] & KEY_REPEAT != 0,
        text: b[OFF_FLAGS] & KEY_TEXT != 0,
        key_code: u16::from_le_bytes([b[OFF_KEY_CODE], b[OFF_KEY_CODE + 1]]),
        scan_code: u16::from_le_bytes([b[OFF_SCAN_CODE], b[OFF_SCAN_CODE + 1]]),
    })
}

/// The record for `event`.
pub const fn encode(event: &KeyEvent) -> [u8; EVENT_SIZE] {
    let mut flags = 0;
    if event.repeat {
        flags |= KEY_REPEAT;
    }
    if event.text {
        flags |= KEY_TEXT;
    }
    let k = event.key_code.to_le_bytes();
    let s = event.scan_code.to_le_bytes();
    [
        MSG_EVENT,
        event.kind,
        event.modifiers,
        flags,
        k[0],
        k[1],
        s[0],
        s[1],
    ]
}

const _: () = assert!(OFF_MSG_TYPE == 0);
const _: () = assert!(OFF_MSG_TYPE + 1 == OFF_EVENT_KIND);
const _: () = assert!(OFF_EVENT_KIND + 1 == OFF_MODIFIERS);
const _: () = assert!(OFF_MODIFIERS + 1 == OFF_FLAGS);
const _: () = assert!(OFF_FLAGS + 1 == OFF_KEY_CODE);
const _: () = assert!(OFF_KEY_CODE + 2 == OFF_SCAN_CODE);
const _: () = assert!(OFF_SCAN_CODE + 2 == EVENT_SIZE);
