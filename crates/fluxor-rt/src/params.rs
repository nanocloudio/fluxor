// Self-describing parameter macro for PIC modules.
//
// Generates from a single definition:
//   - dispatch_param(): TLV tag dispatcher (match on tag → apply closure)
//   - set_defaults(): applies the fixed-size defaults in declaration order
//   - PARAM_SCHEMA: the param schema (`abi::wire::param_schema`), exactly
//     sized, for the `.fmod`
//
// The config tool reads PARAM_SCHEMA from the .fmod to learn param names,
// types, defaults, bounds and enum mappings — no module-specific code
// needed.
//
// Usage:
//
//   define_params! {
//       MyState;
//
//       1, sample_rate, u32, 8000, range 8000..=48000
//           => |s, d, len| { s.sample_rate = p_u32(d, len, 0, 8000); };
//
//       2, waveform, u8, 1, enum { sine=0, saw=1 }
//           => |s, d, len| { s.waveform = p_u8(d, len, 0, 1); };
//
//       3, root, str, 0, max ROOT_MAX
//           => |s, d, len| { s.set_root(d, len); };
//   }
//
// Bounds are inclusive: `max N` (any const expression, such as a const the
// module names) or `range A..=B` (`A` a literal or one const name). An integer's bound is its value's; a `str`'s, a
// `blob`'s and a `str_chunked`'s its bytes; a `u16_array`'s its elements.
// A param declaring none takes its type's ceiling. The composer refuses a
// value outside them at build.
//
// Params MUST be ordered so that dependencies come first (e.g., sample_rate
// before envelope rates that depend on it), because set_defaults applies
// them in declaration order.

/// TLV magic byte
pub const TLV_MAGIC: u8 = 0xFE;

/// TLV version byte
pub const TLV_VERSION: u8 = 0x01;

/// TLV end marker tag
pub const TLV_END: u8 = 0xFF;

// Textually scoped, not `#[macro_export]`: every consumer `include!`s
// this file before invoking the macro, so definition-order visibility
// covers all of them — and a crate-root export would collide the
// moment one crate mounts more than one module core (the test-harness
// and multi-module host builds do exactly that). `allow(unused_macros)`
// because modules without config params still include this file.
#[macro_export]
macro_rules! define_params {
    (
        $state_type:ty;
        $(
            $tag:literal, $name:ident, $ptype:ident, $default:expr
            $(, max $max:expr)?
            $(, range $lo:tt ..= $hi:expr)?
            $(, enum { $($ename:tt = $eval:literal),+ $(,)? })?
            => |$s:ident, $d:ident, $len:ident| $apply:block
        );* $(;)?
    ) => {
        // ================================================================
        // Dispatch: match on TLV tag, execute apply closure
        // ================================================================
        // `#[allow(unused_variables)]` is needed for modules that
        // invoke this macro with no tag entries (e.g. `mesh`, where
        // params are parsed manually) — the function still emits its
        // 4-arg signature, but none of the args are read.
        #[inline(always)]
        /// Dispatch one TLV entry to the per-tag handler. Generated by
        /// the `define_params!` macro.
        ///
        /// # Safety
        /// `d` must be valid for reads of `len` bytes; `s` is the
        /// module's state struct (initialised by `module_new`).
        #[allow(
            unused_variables,
            private_interfaces,
            reason = "unused_variables: when no `$tag => |s, d, len| { … }` entries are supplied (rare, valid for mesh) the function args have no readers. private_interfaces: PIC modules invoke this macro at their crate root with a private $state_type — there is no namespace `pub` could refer to anyway, so the visibility/type mismatch warning is structural rather than real."
        )]
        pub unsafe fn dispatch_param(
            s: &mut $state_type,
            tag: u8,
            d: *const u8,
            len: usize,
        ) {
            match tag {
                $(
                    $tag => {
                        let $s = s;
                        let $d = d;
                        let $len = len;
                        $apply
                    }
                )*
                _ => {}
            }
        }

        // ================================================================
        // Defaults: apply each fixed-size default in declaration order
        // ================================================================
        /// Set every fixed-size parameter (`u8`, `u16`, `u32`) to its
        /// declared default, through its handler. A variable-length
        /// parameter (`str`, `str_chunked`, `blob`, `u16_array`) has no
        /// default value: its handler runs only for a value the params
        /// carry, so an absent one leaves the state as `module_new` set it.
        /// Generated by the `define_params!` macro.
        ///
        /// # Safety
        /// `s` is the module's state struct (initialised by
        /// `module_new`); only its parameter fields are written.
        #[allow(
            unused_variables,
            private_interfaces,
            reason = "see dispatch_param above"
        )]
        pub unsafe fn set_defaults(s: &mut $state_type) {
            $(
                {
                    let size = $crate::define_params!(@type_size $ptype);
                    if size != 0 {
                        let val = ($default as u32).to_le_bytes();
                        dispatch_param(s, $tag, val.as_ptr(), size);
                    }
                }
            )*
        }

        // ================================================================
        // Generic TLV parser: set defaults then dispatch each entry
        // ================================================================
        /// Parse a kernel-supplied TLV blob, applying each entry via
        /// `dispatch_param`. Generated by the `define_params!` macro.
        ///
        /// # Safety
        /// `p` must be valid for reads of `total_len` bytes (the
        /// kernel sizes this from the module's params section).
        #[allow(
            private_interfaces,
            reason = "see dispatch_param above"
        )]
        pub unsafe fn parse_tlv(s: &mut $state_type, p: *const u8, total_len: usize) {
            set_defaults(s);
            if total_len < 4 { return; }
            // `payload_len` at bytes 2-3 is a u16 that writers saturate
            // at 65535 for a blob past 64 KiB, so it is advisory: the
            // walk is bounded by `total_len` (the kernel sizes it from
            // the u32 entry length) and ends at the `$crate::TLV_END` tag.
            let end = total_len;
            let mut off = 4usize;
            while off + 2 <= end {
                let tag = *p.add(off);
                let elen = *p.add(off + 1) as usize;
                off += 2;
                if tag == 0xFF { break; }
                if off + elen <= total_len {
                    dispatch_param(s, tag, p.add(off), elen);
                }
                off += elen;
            }
        }

        // ================================================================
        // The param schema, exactly sized, for the `.fmod`. Its
        // compile-time checks refuse two params on one tag and a bound the
        // type cannot state.
        // ================================================================
        const PARAM_SCHEMA_ENTRIES: &[$crate::abi::wire::param_schema::Entry<'static>] = &[
            $(
                $crate::abi::wire::param_schema::Entry {
                    tag: $tag,
                    ptype: $crate::define_params!(@type_id $ptype),
                    default: ($default as u32),
                    min: $crate::define_params!(@bounds $ptype $(; max $max)? $(; range $lo, $hi)?).0,
                    max: $crate::define_params!(@bounds $ptype $(; max $max)? $(; range $lo, $hi)?).1,
                    name: stringify!($name),
                    enums: &[$($((stringify!($ename), $eval)),+)?],
                },
            )*
        ];

        #[link_section = ".param_schema"]
        #[used]
        pub static PARAM_SCHEMA: [u8; $crate::abi::wire::param_schema::encoded_len(PARAM_SCHEMA_ENTRIES)] =
            $crate::abi::wire::param_schema::encode(PARAM_SCHEMA_ENTRIES);
    };

    // ====================================================================
    // Helper: a param's inclusive bounds, `(min, max)`
    // ====================================================================
    (@bounds $ptype:ident) => {
        (
            0u32,
            $crate::abi::wire::param_schema::type_ceiling($crate::define_params!(@type_id $ptype)),
        )
    };
    (@bounds $ptype:ident; max $max:expr) => { (0u32, ($max) as u32) };
    (@bounds $ptype:ident; range $lo:tt, $hi:expr) => { (($lo) as u32, ($hi) as u32) };

    // ====================================================================
    // Helper: type ID for schema binary
    // ====================================================================
    (@type_id u8) => { $crate::abi::wire::param_schema::ty::U8 };
    (@type_id u16) => { $crate::abi::wire::param_schema::ty::U16 };
    (@type_id u32) => { $crate::abi::wire::param_schema::ty::U32 };
    (@type_id str) => { $crate::abi::wire::param_schema::ty::STR };
    (@type_id u16_array) => { $crate::abi::wire::param_schema::ty::U16_ARRAY };
    (@type_id blob) => { $crate::abi::wire::param_schema::ty::BLOB };
    // A `str` whose handler APPENDS each chunk it is given. The packer
    // splits a value longer than one TLV entry across several entries
    // under the same tag; that only reassembles for a handler that
    // appends, so a plain `str` is refused past one entry at build time
    // and this type is the opt-in for the handlers that do accumulate.
    (@type_id str_chunked) => { $crate::abi::wire::param_schema::ty::STR_CHUNKED };

    // ====================================================================
    // Helper: type size for set_defaults buffer (0 = skip for var-length)
    // ====================================================================
    (@type_size u8) => { 1usize };
    (@type_size u16) => { 2usize };
    (@type_size u32) => { 4usize };
    (@type_size str) => { 0usize };
    (@type_size u16_array) => { 0usize };
    (@type_size blob) => { 0usize };
    (@type_size str_chunked) => { 0usize };
}
